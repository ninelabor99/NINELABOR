const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = p => fs.readFileSync(p,'utf8');
const rules=read('firestore.rules');
const block=rules.split('match /subscription_requests/{requestId} {')[1];
assert(block, 'legacy requests rules absent');
assert.match(block,/allow create, update, delete: if false;/);
assert(!/allow create: if isSignedIn/.test(block));
const admin=read('src/components/dashboard/admin/AdminSubscriptionsView.tsx');
assert.match(admin,/LEGACY_REQUESTS_ENABLED = false/);
assert.match(admin,/LEGACY_REQUESTS_ENABLED && subViewTab === 'requests'/);
const dashboard=read('src/components/dashboard/admin/AdminDashboardSummary.tsx');
assert(!dashboard.includes('미수금 없음'));
const policies=read('src/config/policies.ts');
const modal=read('src/components/common/PolicyModal.tsx');
assert(!policies.includes('정기결제 및 구독 해지 안내'));
assert(!modal.includes('매월 약정일에 정기 결제'));
assert(policies.includes('현재 자동결제 기능은 연동되어 있지 않습니다.'));
assert(read('src/components/dashboard/pricing/PricingView.tsx').includes('카드 등록, 자동결제, 온라인 결제를 제공하지 않습니다.'));
assert(modal.includes('POLICY_SECTIONS[currentPolicy.id]'));
assert(read('src/components/dashboard/pricing/PricingView.tsx').includes('온라인 결제 및 셀프 플랜 신청을 제공하지 않는'));
console.log('PASS: offline-only plan flow, legacy request writes disabled, policy/dashboard consistency');
